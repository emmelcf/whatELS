#!/usr/bin/env python3
"""
scripts/embed_controller_assets.py
Pre-build script for whatELS.
1. Reads data/presets/profiles.json and generates src/motion/SystemProfilesJson.h
2. Gzips data/www/{index.html, style.css, app.js} and generates src/web/ControllerWebAssets.h
"""

import os
import gzip
import sys

def get_project_dir():
    # If running inside PlatformIO SCons
    try:
        Import("env")
        return env.subst("$PROJECT_DIR")
    except NameError:
        return os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))

def generate_profiles_header(project_dir):
    src_json = os.path.join(project_dir, "data", "presets", "profiles.json")
    out_h = os.path.join(project_dir, "src", "motion", "SystemProfilesJson.h")

    if not os.path.isfile(src_json):
        print(f"[embed_controller_assets] Warning: {src_json} not found.")
        return

    with open(src_json, "r", encoding="utf-8") as f:
        json_content = f.read()

    # Generate SystemProfilesJson.h with C++ raw string literal
    content = f"""// Auto-generated by scripts/embed_controller_assets.py from data/presets/profiles.json
// DO NOT EDIT DIRECTLY.
#pragma once
#if defined(ESP32) || defined(ARDUINO)
#include <Arduino.h>
#else
#include <cstdint>
#ifndef PROGMEM
#define PROGMEM
#endif
#endif

static const char SYSTEM_PROFILES_JSON[] PROGMEM = R"rawliteral({json_content})rawliteral";
"""

    # Check if target already has identical content to prevent unnecessary rebuilds
    if os.path.isfile(out_h):
        with open(out_h, "r", encoding="utf-8") as f:
            if f.read() == content:
                return

    os.makedirs(os.path.dirname(out_h), exist_ok=True)
    with open(out_h, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"[embed_controller_assets] Generated {out_h} ({len(json_content)} bytes)")

def gzip_to_c_array(file_path):
    with open(file_path, "rb") as f:
        raw_bytes = f.read()
    gz_bytes = gzip.compress(raw_bytes, 9)
    hex_str = ", ".join(f"0x{b:02x}" for b in gz_bytes)
    return hex_str, len(raw_bytes), len(gz_bytes)

def generate_web_assets_header(project_dir):
    www_dir = os.path.join(project_dir, "data", "www")
    out_h = os.path.join(project_dir, "src", "web", "ControllerWebAssets.h")

    index_html = os.path.join(www_dir, "index.html")
    style_css = os.path.join(www_dir, "style.css")
    app_js = os.path.join(www_dir, "app.js")

    if not (os.path.isfile(index_html) and os.path.isfile(style_css) and os.path.isfile(app_js)):
        print(f"[embed_controller_assets] Warning: www assets not found in {www_dir}.")
        return

    idx_hex, idx_raw, idx_gz = gzip_to_c_array(index_html)
    css_hex, css_raw, css_gz = gzip_to_c_array(style_css)
    js_hex, js_raw, js_gz = gzip_to_c_array(app_js)

    content = f"""// Auto-generated by scripts/embed_controller_assets.py from data/www/
// DO NOT EDIT DIRECTLY.
#pragma once
#if defined(ESP32) || defined(ARDUINO)
#include <Arduino.h>
#else
#include <cstdint>
#ifndef PROGMEM
#define PROGMEM
#endif
#endif

// index.html: {idx_raw} bytes raw -> {idx_gz} bytes gzipped
static const uint32_t WWW_INDEX_HTML_RAW_LEN = {idx_raw};
static const uint32_t WWW_INDEX_HTML_GZ_LEN = {idx_gz};
static const uint8_t WWW_INDEX_HTML_GZ[{idx_gz}] PROGMEM = {{
  {idx_hex}
}};

// style.css: {css_raw} bytes raw -> {css_gz} bytes gzipped
static const uint32_t WWW_STYLE_CSS_RAW_LEN = {css_raw};
static const uint32_t WWW_STYLE_CSS_GZ_LEN = {css_gz};
static const uint8_t WWW_STYLE_CSS_GZ[{css_gz}] PROGMEM = {{
  {css_hex}
}};

// app.js: {js_raw} bytes raw -> {js_gz} bytes gzipped
static const uint32_t WWW_APP_JS_RAW_LEN = {js_raw};
static const uint32_t WWW_APP_JS_GZ_LEN = {js_gz};
static const uint8_t WWW_APP_JS_GZ[{js_gz}] PROGMEM = {{
  {js_hex}
}};
"""

    if os.path.isfile(out_h):
        with open(out_h, "r", encoding="utf-8") as f:
            if f.read() == content:
                return

    os.makedirs(os.path.dirname(out_h), exist_ok=True)
    with open(out_h, "w", encoding="utf-8") as f:
        f.write(content)
    total_raw = idx_raw + css_raw + js_raw
    total_gz = idx_gz + css_gz + js_gz
    print(f"[embed_controller_assets] Generated {out_h} ({total_raw} raw -> {total_gz} gzipped)")

