def generate_presets_header(project_dir):
    presets_dir = os.path.join(project_dir, "data", "presets")
    out_h = os.path.join(project_dir, "src", "core", "SystemPresetsJson.h")

    # If presets dir does not exist, run generator
    threads_dir = os.path.join(presets_dir, "threads")
    tapers_dir = os.path.join(presets_dir, "tapers")
    if not (os.path.isdir(threads_dir) and os.path.isdir(tapers_dir)):
        import subprocess
        gen_script = os.path.join(project_dir, "scripts", "generate_presets.py")
        if os.path.isfile(gen_script):
            subprocess.run([sys.executable, gen_script], check=True)

    if not os.path.isdir(presets_dir):
        print(f"[embed_controller_assets] Warning: {presets_dir} not found.")
        return

    import json
    entries = []
    literals = []

    # Scan domains (threads, tapers, etc.)
    for domain in sorted(os.listdir(presets_dir)):
        domain_path = os.path.join(presets_dir, domain)
        if not os.path.isdir(domain_path):
            continue
        for fname in sorted(os.listdir(domain_path)):
            if not fname.endswith(".json"):
                continue
            cat_name = fname[:-5] # strip .json
            fpath = os.path.join(domain_path, fname)
            with open(fpath, "r", encoding="utf-8") as f:
                raw_json = f.read()
            # Minify JSON to save ROM flash and RAM heap
            try:
                minified = json.dumps(json.loads(raw_json), separators=(',', ':'))
            except Exception as e:
                print(f"[embed_controller_assets] Error minifying {fpath}: {e}")
                minified = raw_json

            var_name = f"PRESET_{domain.upper()}_{cat_name.upper()}_JSON"
            literals.append(f"static const char {var_name}[] PROGMEM = R\"rawliteral({minified})rawliteral\";")
            entries.append((domain, cat_name, var_name))

    catalog_entries = ",\n".join(
        f'  {{ "{domain}", "{cat}", {var_name} }}' for domain, cat, var_name in entries
    )

    header_body = "\n\n".join(literals)

    content = f"""// Auto-generated by scripts/embed_controller_assets.py from data/presets/
// DO NOT EDIT DIRECTLY.
#pragma once
#if defined(ESP32) || defined(ARDUINO)
#include <Arduino.h>
#else
#include <cstdint>
#ifndef PROGMEM
#define PROGMEM
#endif
#endif

struct SystemPresetCatalogEntry {{
  const char* domain;
  const char* catalog;
  const char* json;
}};

{header_body}

static const SystemPresetCatalogEntry SYSTEM_PRESET_ENTRIES[] = {{
{catalog_entries}
}};
static const size_t SYSTEM_PRESET_ENTRY_COUNT = sizeof(SYSTEM_PRESET_ENTRIES) / sizeof(SYSTEM_PRESET_ENTRIES[0]);
"""

    if os.path.isfile(out_h):
        with open(out_h, "r", encoding="utf-8") as f:
            if f.read() == content:
                return

    os.makedirs(os.path.dirname(out_h), exist_ok=True)
    with open(out_h, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"[embed_controller_assets] Generated {out_h} ({len(entries)} preset catalogs embedded)")

def main():
    project_dir = get_project_dir()
    generate_profiles_header(project_dir)
    generate_schema_header(project_dir)
    generate_web_assets_header(project_dir)
    generate_presets_header(project_dir)

main()

